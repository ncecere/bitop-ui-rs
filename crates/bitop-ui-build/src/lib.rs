//! CSS Modules for Rust build scripts, without Node.
//!
//! Call [`Build::run`] from `build.rs`. It compiles every `*.module.css` file under the source
//! directory with Lightning CSS in CSS Modules mode and writes two files to `OUT_DIR`:
//!
//! - a stylesheet holding the global files followed by every module, with class names scoped;
//! - a Rust file with one module per CSS file and one constant per class, to `include!`.
//!
//! A class that does not exist in the CSS is then a compile error in Rust.

use std::{
    collections::BTreeMap,
    env,
    fmt::Write as _,
    fs,
    path::{Path, PathBuf},
};

use lightningcss::{
    css_modules::{Config, Pattern},
    stylesheet::{MinifyOptions, ParserOptions, PrinterOptions, StyleSheet},
};

/// Configuration for one crate's stylesheet.
pub struct Build {
    src_dir: PathBuf,
    globals: Vec<PathBuf>,
    stylesheet: String,
    rust_file: String,
    script: Option<String>,
    script_preludes: Vec<PathBuf>,
    minify: bool,
}

impl Build {
    /// Scans `src_dir`, relative to the crate root, for `*.module.css` files.
    pub fn new(src_dir: impl Into<PathBuf>) -> Self {
        Self {
            src_dir: src_dir.into(),
            globals: Vec::new(),
            stylesheet: "styles.css".to_owned(),
            rust_file: "css_modules.rs".to_owned(),
            script: None,
            script_preludes: Vec::new(),
            minify: env::var("PROFILE").is_ok_and(|profile| profile == "release"),
        }
    }

    /// Adds an unscoped stylesheet, such as design tokens. Globals come first, in call order.
    pub fn global(mut self, path: impl Into<PathBuf>) -> Self {
        self.globals.push(path.into());
        self
    }

    /// Names the stylesheet written to `OUT_DIR`. Defaults to `styles.css`.
    pub fn stylesheet(mut self, name: impl Into<String>) -> Self {
        self.stylesheet = name.into();
        self
    }

    /// Bundles every `*.js` file under the source directory into one script named
    /// `name` in `OUT_DIR`. Files are joined in path order, each in its own block so
    /// that their names cannot clash.
    pub fn script(mut self, name: impl Into<String>) -> Self {
        self.script = Some(name.into());
        self
    }

    /// Adds a script that goes before the component scripts, in call order, and outside
    /// any block, so that what it declares is visible to all of them.
    pub fn script_prelude(mut self, path: impl Into<PathBuf>) -> Self {
        self.script_preludes.push(path.into());
        self
    }

    /// Joins the prelude and component scripts. Prints `cargo:rerun-if-changed` lines.
    pub fn bundle_script(&self) -> Result<String, String> {
        let read =
            |path: &Path| fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()));
        let mut js = String::from("// Generated by bitop-ui-build. Do not edit.\n");
        for prelude in &self.script_preludes {
            println!("cargo:rerun-if-changed={}", prelude.display());
            writeln!(
                js,
                "// {}\n{}",
                prelude.display(),
                read(prelude)?.trim_end()
            )
            .unwrap();
        }
        let mut scripts = Vec::new();
        collect(&self.src_dir, ".js", &mut scripts)?;
        scripts.sort();
        for path in scripts {
            writeln!(
                js,
                "// {}\n{{\n{}\n}}",
                path.display(),
                read(&path)?.trim_end()
            )
            .unwrap();
        }
        Ok(js)
    }

    /// Compiles the stylesheet and the Rust constants into `OUT_DIR`.
    pub fn run(self) -> Result<(), String> {
        let out_dir = PathBuf::from(env::var("OUT_DIR").map_err(|e| e.to_string())?);
        let output = self.compile()?;
        write_if_changed(&out_dir.join(&self.stylesheet), &output.css)?;
        write_if_changed(&out_dir.join(&self.rust_file), &output.rust)?;
        if let Some(script) = &self.script {
            write_if_changed(&out_dir.join(script), &self.bundle_script()?)?;
        }
        Ok(())
    }

    /// Compiles without touching `OUT_DIR`. Prints `cargo:rerun-if-changed` lines.
    pub fn compile(&self) -> Result<Output, String> {
        let mut css = String::new();
        let mut rust = String::from("// Generated by bitop-ui-build. Do not edit.\n");

        println!("cargo:rerun-if-changed={}", self.src_dir.display());
        for global in &self.globals {
            println!("cargo:rerun-if-changed={}", global.display());
            css.push_str(&transform(global, None, self.minify)?.0);
            css.push('\n');
        }

        let mut modules = Vec::new();
        collect(&self.src_dir, ".module.css", &mut modules)?;
        modules.sort();

        let mut seen = BTreeMap::new();
        for path in modules {
            let name = module_name(&path)?;
            if let Some(previous) = seen.insert(name.clone(), path.clone()) {
                return Err(format!(
                    "{} and {} both produce the module `{name}`",
                    previous.display(),
                    path.display()
                ));
            }
            let (module_css, classes) = transform(&path, Some(&name), self.minify)?;
            css.push_str(&module_css);
            css.push('\n');

            writeln!(rust, "#[allow(dead_code)]\npub mod {name} {{").unwrap();
            for (local, scoped) in classes {
                writeln!(
                    rust,
                    "    pub const {}: &str = {scoped:?};",
                    const_name(&local)
                )
                .unwrap();
            }
            rust.push_str("}\n");
        }

        Ok(Output { css, rust })
    }
}

/// The compiled stylesheet and generated Rust source.
pub struct Output {
    pub css: String,
    pub rust: String,
}

fn collect(dir: &Path, suffix: &str, found: &mut Vec<PathBuf>) -> Result<(), String> {
    let entries = fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    for entry in entries {
        let path = entry.map_err(|e| e.to_string())?.path();
        if path.is_dir() {
            collect(&path, suffix, found)?;
        } else if path.to_string_lossy().ends_with(suffix) {
            found.push(path);
        }
    }
    Ok(())
}

/// Returns the CSS and the local-to-scoped class map. `module` is the Rust module name
/// for a CSS module, or `None` for an unscoped stylesheet.
fn transform(
    path: &Path,
    module: Option<&str>,
    minify: bool,
) -> Result<(String, BTreeMap<String, String>), String> {
    let source = fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let filename = path.to_string_lossy().into_owned();
    let fail = |e: String| format!("{filename}: {e}");

    // Scoped names read `button_root_<hash>`: the module, the class, then a hash of the path.
    let pattern = module.map(|name| format!("{name}_[local]_[hash]"));
    let css_modules = match &pattern {
        Some(pattern) => Some(Config {
            pattern: Pattern::parse(pattern).map_err(|e| fail(e.to_string()))?,
            ..Config::default()
        }),
        None => None,
    };
    let mut sheet = StyleSheet::parse(
        &source,
        ParserOptions {
            filename: filename.clone(),
            css_modules,
            ..ParserOptions::default()
        },
    )
    .map_err(|e| fail(e.to_string()))?;
    if minify {
        sheet
            .minify(MinifyOptions::default())
            .map_err(|e| fail(e.to_string()))?;
    }
    let result = sheet
        .to_css(PrinterOptions {
            minify,
            ..PrinterOptions::default()
        })
        .map_err(|e| fail(e.to_string()))?;

    let mut classes = BTreeMap::new();
    for (local, export) in result.exports.unwrap_or_default() {
        // The generated constant holds one class name. `composes` needs several, and
        // across files it needs a resolver, so reject it instead of dropping styles.
        if !export.composes.is_empty() {
            return Err(fail(format!(
                "`.{local}` uses `composes`, which is not supported; \
                 apply both classes in the component instead"
            )));
        }
        classes.insert(local, export.name);
    }
    Ok((result.code, classes))
}

/// `src/components/alert_dialog.module.css` becomes `alert_dialog`.
fn module_name(path: &Path) -> Result<String, String> {
    let file = path
        .file_name()
        .and_then(|name| name.to_str())
        .and_then(|name| name.strip_suffix(".module.css"))
        .ok_or_else(|| format!("{}: not a CSS module", path.display()))?;
    let name = file.replace('-', "_");
    let valid = name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
        && name.chars().next().is_some_and(|c| !c.is_ascii_digit());
    if valid {
        Ok(name)
    } else {
        Err(format!(
            "{}: file name is not a Rust identifier",
            path.display()
        ))
    }
}

/// `popup-arrow` and `popupArrow` both become `POPUP_ARROW`.
fn const_name(class: &str) -> String {
    let mut name = String::new();
    let mut previous_lower = false;
    for c in class.chars() {
        if c == '-' || c == '_' {
            name.push('_');
            previous_lower = false;
        } else {
            if c.is_ascii_uppercase() && previous_lower {
                name.push('_');
            }
            name.push(c.to_ascii_uppercase());
            previous_lower = c.is_ascii_lowercase() || c.is_ascii_digit();
        }
    }
    name
}

fn write_if_changed(path: &Path, contents: &str) -> Result<(), String> {
    if fs::read_to_string(path).is_ok_and(|current| current == contents) {
        return Ok(());
    }
    fs::write(path, contents).map_err(|e| format!("{}: {e}", path.display()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn const_names() {
        assert_eq!(const_name("root"), "ROOT");
        assert_eq!(const_name("popup-arrow"), "POPUP_ARROW");
        assert_eq!(const_name("popupArrow"), "POPUP_ARROW");
        assert_eq!(const_name("h2"), "H2");
    }

    #[test]
    fn scopes_classes_and_keeps_globals() {
        let dir = env::temp_dir().join(format!("bitop-ui-build-{}", std::process::id()));
        fs::create_dir_all(dir.join("src")).unwrap();
        fs::write(dir.join("tokens.css"), ":root { --accent: blue; }").unwrap();
        fs::write(
            dir.join("src/button.module.css"),
            ".root { color: var(--accent); &[data-disabled] { opacity: 0.5; } }\n.icon-slot {}",
        )
        .unwrap();

        let output = Build::new(dir.join("src"))
            .global(dir.join("tokens.css"))
            .compile()
            .unwrap();
        fs::remove_dir_all(&dir).unwrap();

        assert!(output.css.contains("--accent: blue"));
        assert!(output.rust.contains("pub mod button {"));
        assert!(
            output
                .rust
                .contains("pub const ICON_SLOT: &str = \"button_icon-slot_")
        );
        let scoped = output
            .rust
            .split("pub const ROOT: &str = \"")
            .nth(1)
            .and_then(|rest| rest.split('"').next())
            .unwrap();
        assert!(scoped.starts_with("button_root_"));
        assert!(output.css.contains(&format!(".{scoped}")));
        assert!(!output.css.contains(".root"));
    }
}
